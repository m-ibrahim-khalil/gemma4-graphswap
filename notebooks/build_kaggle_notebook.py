DRIVER_BANNER = "# ---------------------------------------------------------------- driver"

# The pre-registration is cited by its file hash and its timestamp proof, never by a commit: the
# public repository is one squashed commit, so a development-history hash would not resolve.
# tests/test_kaggle_notebook.py checks the hash against the file and docs/preregistration.sha256.
PREREGISTRATION_SHA256 = "83cda15eb084d9d6462096977e6a295c1a9c6d7d9970bf595a6604d65f24e92b"
PREREGISTRATION_OTS = "docs/preregistration.sha256.ots"
PREREGISTRATION_STAMP = "block 973351 (2026-10-27 05:26 UTC)"  # earliest Bitcoin attestation
DATASET_SLUG = "gemma4-graphswap-results"


def digest(text: str) -> str:
    """Identity of a copied source: its sha256, the first 12 hex digits.

    Not the commit that last touched the file: the notebook is committed together with the
    sources it copies, so a commit hash in it would always name the commit before its own.
    The digest is of the source file as read, so it is exact and stays correct.
    """
    return hashlib.sha256(text.encode()).hexdigest()[:12]


def stats_source() -> str:
    """``graphswap/stats.py``, verbatim, under a one-line provenance comment."""
    module = STATS.read_text()
    return (f"# Vendored verbatim from graphswap/stats.py of the graph resolution study repo "
            f"(sha256 {digest(module)}; rules pre-registered in docs/preregistration.md, "
            f"sha256 {PREREGISTRATION_SHA256}).\n"
            f"# Pre-registered, do not edit here; tests/test_kaggle_notebook.py fails if this "
            f"copy and the module differ.\n\n" + module)


def analysis_source() -> str:
    """``notebooks/analysis.py`` up to its driver, with the two module-only lines dropped."""
    text = ANALYSIS.read_text()
    head, sep, _ = text.partition(DRIVER_BANNER)
    if not sep:
        raise ValueError(f"{ANALYSIS}: driver banner not found, cannot cut the copy")
    for line in DROP_LINES:
        if line not in head:
            raise ValueError(f"{ANALYSIS}: expected line to drop is missing: {line!r}")
        head = head.replace(line, "", 1)
    return (f"# Vendored from notebooks/analysis.py of the graph resolution study repo "
            f"(sha256 {digest(text)} of the full file; this copy is that file without its "
            f"file-writing driver).\n"
            f"# Generated by notebooks/build_kaggle_notebook.py; "
            f"tests/test_kaggle_notebook.py fails if this copy and the module differ.\n\n"
            + head.rstrip("\n") + "\n")



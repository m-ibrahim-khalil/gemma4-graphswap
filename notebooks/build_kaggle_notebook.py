def build() -> nbformat.NotebookNode:
    nb = nbformat.v4.new_notebook()
    nb.metadata = {"kernelspec": {"display_name": "Python 3", "language": "python",
                                  "name": "python3"},
                   "language_info": {"name": "python"}}
    sources = {"@STATS@": stats_source, "@ANALYSIS@": analysis_source}
    for i, (kind, text) in enumerate(CELLS):
        text = sources[text]() if text in sources else text
        cell = (nbformat.v4.new_markdown_cell if kind == "markdown"
                else nbformat.v4.new_code_cell)(text.rstrip("\n"))
        cell["id"] = f"cell-{i:02d}"  # fixed, so regenerating gives a byte-identical file
        nb.cells.append(cell)
    return nb


def notebook_text() -> str:
    return nbformat.writes(build(), version=nbformat.NO_CONVERT) + "\n"


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--out", type=Path, default=OUT)
    p.add_argument("--check", action="store_true", help="only report whether --out is up to date")
    args = p.parse_args(argv)
    text = notebook_text()
    if args.check:
        current = args.out.read_text() if args.out.exists() else ""
        print("up to date" if current == text else f"STALE: regenerate {args.out}")
        raise SystemExit(0 if current == text else 1)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"wrote {args.out} ({len(build().cells)} cells, outputs cleared)")


if __name__ == "__main__":
    main()

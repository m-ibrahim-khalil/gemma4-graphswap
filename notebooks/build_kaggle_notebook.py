"""Generate ``kaggle/analysis_notebook.ipynb``, the public reproduction notebook.

    uv run python notebooks/build_kaggle_notebook.py [--out PATH] [--check]

The notebook must run on Kaggle with no network and no repo, so it cannot import
``graphswap`` or ``notebooks/analysis.py``. Instead it carries a copy of both, generated
here: the pre-registered statistics verbatim from ``graphswap/stats.py``, and
``notebooks/analysis.py`` with three edits (listed in ``analysis_source``) that a module
needs and a cell cannot have. Every number therefore still has exactly one definition in
this repo; ``tests/test_kaggle_notebook.py`` fails if the committed notebook drifts from it.

Outputs are never stored: the notebook is committed cleared, like ``notebooks/analysis.ipynb``.
"""


def repo_results() -> Path:
    """`results/` of the study repo, found by walking up from the working directory."""
    for parent in (Path.cwd(), *Path.cwd().parents):
        if (parent / "pyproject.toml").is_file():
            return parent / "results"
    return Path.cwd() / "results"


def mounted_dirs(root: Path, depth: int = 4):
    """Every directory below root down to `depth` levels, shallowest first, sorted per level.

    Directories only, and symlinks are not followed.
    """
    level = [root]
    for _ in range(depth):
        children = []
        for parent in level:
            if parent.is_dir():
                with os.scandir(parent) as entries:
                    children += [Path(e.path) for e in entries if e.is_dir(follow_symlinks=False)]
        level = sorted(children)
        yield from level



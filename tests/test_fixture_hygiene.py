"""No real agent-trace content ships under tests/fixtures/.

The two trace fixtures used to be trimmed copies of real competition runs; they are now
generated by tests/fixtures/make_traces.py and name only invented repos. The rule is
tests/hygiene.py, shared with the Kaggle-path checks in test_release_hygiene.py.
"""

from pathlib import Path

import pytest
from hygiene import check_fixture_is_synthetic

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "tests" / "fixtures"


def _files() -> list[Path]:
    return sorted(p for p in FIXTURES.rglob("*")
                  if p.is_file() and "__pycache__" not in p.parts)


def test_the_fixture_files_are_found():
    names = {p.relative_to(FIXTURES).as_posix() for p in _files()}
    assert {"make_traces.py", "graphs/r_abc.json", "traces/run_manifest.json",
            "traces/task_results.jsonl", "traces/traces/trace_widgetlib_101.json",
            "traces/traces/trace_gearbox_202.json"} <= names


@pytest.mark.parametrize("path", _files(), ids=lambda p: p.relative_to(FIXTURES).as_posix())
def test_fixture_carries_no_real_trace_content(path):
    check_fixture_is_synthetic(path.read_text(errors="replace"))


PASSES = [
    '{"node_name": "widgetlib.frame.Frame.render"}',
    "a richer payload than the request needed",  # not the repo: no word boundary
    "rich-text, requested, prerequests",
    '{"instance_id": "widgetlib_101", "repo": "acme/widgetlib"}',
    "see /kaggle/input/<slug>/tasks.jsonl",
]
SMUGGLED = [
    # invented node ids and queries: only the repo-name token has to trip the rule
    '{"node_name": "rich.widgets.Decoder.decode_line"}',
    '{"query": "widget parser", "repo": "psf/requests"}',
    '"neighbors": ["psf/requests;widgetlib.models.PreparedThing"]',
    "model_name: /kaggle/input/real-competition/models/m/2",  # the mount a trace records
    '{"repo": "Textualize/rich"}',
    "FASTAPI_14301",
    '{"instance_id": "rich_3278", "repo": "Textualize/rich"}',  # the old fixture's id
    "httpx/_client.py",
]


@pytest.mark.parametrize("text", PASSES)
def test_synthetic_text_passes(text):
    check_fixture_is_synthetic(text)


@pytest.mark.parametrize("text", SMUGGLED)
def test_real_trace_content_fails(text):
    with pytest.raises(AssertionError):
        check_fixture_is_synthetic(text)
